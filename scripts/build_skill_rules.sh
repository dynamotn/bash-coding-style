#!/usr/bin/env bash
# @file build_skill_rules.sh
# @brief Build the rule references of the agent skill from the guide
# @description
#   The skill in `skills/bash-coding-style` is installed on its own, without the
#   README, so it carries the tips of the guide in `references/`: one file per
#   chapter, named after the anchor of the chapter, holding the tips of each
#   section under a link to that section of the README on GitHub. The tips are
#   copied as written, rule codes included, so an agent finds the tip behind a
#   finding with `rg BSG010`.
#
#   `SKILL.md` lists the reference files by hand, so a chapter it does not name
#   is an error. With `--check`, nothing is written: the script only fails when
#   a file would change.
if ((BASH_VERSINFO[0] < 4 || (BASH_VERSINFO[0] == 4 && BASH_VERSINFO[1] < 4))); then
  printf 'This script needs Bash 4.4 or newer, found %s\n' "${BASH_VERSION}" >&2
  exit 1
fi
set -euo pipefail
shopt -s inherit_errexit

SCRIPT_DIR="$(CDPATH='' cd -P -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
readonly SCRIPT_DIR
REPO_DIR="$(CDPATH='' cd -P -- "${SCRIPT_DIR}/.." && pwd)"
readonly REPO_DIR
readonly README="${REPO_DIR}/README.md"
readonly SKILL_DIR="${REPO_DIR}/skills/bash-coding-style"
readonly REFERENCES_DIR="${SKILL_DIR}/references"
readonly GUIDE_URL="https://github.com/dynamotn/bash-coding-style/blob/main/README.md"

# A heading of the table of contents, and a tip of the guide.
readonly TOC_ENTRY='^ *- \[(.*)\]\(#([^)]+)\)$'
readonly TIP='^> (- (✔️|❌|⚠️) .*)$'

#######################################
# @description Write one reference file per chapter of the guide into a directory.
# @arg $1 string Directory that receives the files
# @stdout Nothing
# @exitcode 1 A heading of the guide is missing from its table of contents
#######################################
function _build_into {
  local out_dir
  out_dir="$1"

  local -A anchors=()
  local line title in_toc=false
  while IFS= read -r line || [[ -n "${line}" ]]; do
    case "${line}" in
      '<!-- toc -->') in_toc=true ;;
      '<!-- tocstop -->') break ;;
      *)
        if [[ "${in_toc}" == true && "${line}" =~ ${TOC_ENTRY} ]]; then
          anchors["${BASH_REMATCH[1]}"]="${BASH_REMATCH[2]}"
        fi
        ;;
    esac
  done < "${README}"

  # The heading of a section is written before its first tip, so a section
  # without tips leaves no trace.
  local file="" section="" heading_written=false
  while IFS= read -r line || [[ -n "${line}" ]]; do
    if [[ "${line}" == '## '* ]]; then
      title="${line#'## '}"
      file=""
      section=""
      [[ -v "anchors[${title}]" ]] || continue
      file="${out_dir}/${anchors[${title}]}.md"
    elif [[ "${line}" == '### '* && -n "${file}" ]]; then
      section="${line#'### '}"
      heading_written=false
      if [[ ! -v "anchors[${section}]" ]]; then
        printf 'Section missing from the table of contents: %s\n' "${section}" >&2
        return 1
      fi
    elif [[ "${line}" =~ ${TIP} && -n "${section}" ]]; then
      if [[ ! -f "${file}" ]]; then
        printf '<!-- Generated by scripts/build_skill_rules.sh from README.md, do not edit -->\n\n# %s\n' \
          "${title}" > "${file}"
      fi
      if [[ "${heading_written}" == false ]]; then
        printf '\n## [%s](%s#%s)\n\n' "${section}" "${GUIDE_URL}" "${anchors[${section}]}" >> "${file}"
        heading_written=true
      fi
      printf '%s\n' "${BASH_REMATCH[1]}" >> "${file}"
    fi
  done < "${README}"
}

#######################################
# @description Build the references, then check them or replace the old ones.
# @arg $1 string Optional `--check`, to report instead of writing
# @exitcode 0 The references are up to date, or were updated
# @exitcode 1 The references are out of date under `--check`, or cannot be built
#######################################
function _main {
  local check=false
  case "${1-}" in
    --check) check=true ;;
    '') ;;
    *)
      printf 'Usage: %s [--check]\n' "${0##*/}" >&2
      return 1
      ;;
  esac

  local work_dir
  work_dir="$(mktemp -d)"
  # shellcheck disable=SC2064 # expand now: work_dir is local
  trap "rm -rf -- '${work_dir}'" EXIT
  _build_into "${work_dir}"

  local -a unlisted=()
  local reference
  for reference in "${work_dir}"/*.md; do
    [[ -e "${reference}" ]] || continue
    reference="references/${reference##*/}"
    grep -qF -- "(${reference})" "${SKILL_DIR}/SKILL.md" || unlisted+=("${reference}")
  done
  if ((${#unlisted[@]} > 0)); then
    printf 'SKILL.md does not list %s\n' "${unlisted[*]}" >&2
    return 1
  fi

  if diff -rq -- "${work_dir}" "${REFERENCES_DIR}" &> /dev/null; then
    printf 'Skill references are up to date\n' >&2
    return 0
  fi
  if [[ "${check}" == true ]]; then
    printf 'Skill references are out of date; run: bash ./scripts/build_skill_rules.sh\n' >&2
    return 1
  fi
  mkdir -p -- "${REFERENCES_DIR}"
  rm -f -- "${REFERENCES_DIR}"/*.md
  cp -- "${work_dir}"/*.md "${REFERENCES_DIR}/"
  printf 'Updated %s\n' "${REFERENCES_DIR#"${REPO_DIR}/"}" >&2
}

_main "$@"
